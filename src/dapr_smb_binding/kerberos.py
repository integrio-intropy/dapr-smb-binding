"""Kerberos plumbing: a generated krb5.conf, keytab files, and a startup check.

Tickets never touch disk: pyspnego gets a TGT into a private MEMORY ccache at
every SMB session setup, from the password or the keytab. What is process-wide
is the krb5 config file, so every component instance adds its realm to one
generated file.
"""

from __future__ import annotations

import os
import pathlib
import threading

RUNTIME_DIR_ENV = "SMB_BINDING_RUNTIME_DIR"
DEFAULT_RUNTIME_DIR = "/tmp/dapr-smb-binding"  # noqa: S108 - an emptyDir (medium: Memory) in Kubernetes

_lock = threading.Lock()
# component name -> (realm, kdcs, file server)
_realms: dict[str, tuple[str, tuple[str, ...], str]] = {}


def runtime_dir() -> pathlib.Path:
    d = pathlib.Path(os.environ.get(RUNTIME_DIR_ENV) or DEFAULT_RUNTIME_DIR)
    d.mkdir(mode=0o700, parents=True, exist_ok=True)
    return d


def render(realms: list[tuple[str, tuple[str, ...], str]]) -> str:
    kdcs: dict[str, list[str]] = {}
    for realm, ks, _ in realms:
        kdcs.setdefault(realm, []).extend(k for k in ks if k not in kdcs[realm])
    lines = ["# Generated by dapr-smb-binding. Do not edit.", "[libdefaults]"]
    if realms:
        lines.append(f"    default_realm = {realms[0][0]}")
    lines += [
        # KDCs from DNS only for a realm configured without explicit kdcs.
        f"    dns_lookup_kdc = {'true' if any(not v for v in kdcs.values()) else 'false'}",
        "    dns_lookup_realm = false",
        "    dns_canonicalize_hostname = false",
        "    rdns = false",
        "    udp_preference_limit = 1",  # TCP only: works through Skupper and with large PACs
        "",
        "[realms]",
    ]
    for realm, ks in kdcs.items():
        lines += [f"    {realm} = {{", *(f"        kdc = {k}" for k in ks), "    }"]
    lines += ["", "[domain_realm]", *(f"    {server} = {realm}" for realm, _, server in realms)]
    return "\n".join(lines) + "\n"


def register(component: str, realm: str, kdcs: tuple[str, ...], server: str) -> None:
    with _lock:
        _realms[component] = (realm, kdcs, server)
        _write()


def unregister(component: str) -> None:
    with _lock:
        if _realms.pop(component, None):
            _write()


def _write() -> None:
    path = runtime_dir() / "krb5.conf"
    tmp = path.with_suffix(".tmp")
    tmp.write_text(render(list(_realms.values())))
    tmp.replace(path)
    # MIT krb5 reads KRB5_CONFIG for every new context, and pyspnego makes one per
    # session setup, so rewriting the file is enough.
    os.environ["KRB5_CONFIG"] = str(path)
    os.environ.setdefault("KRB5CCNAME", "MEMORY:dapr-smb-binding")


def write_keytab(component: str, data: bytes) -> pathlib.Path:
    """Write the keytab, readable by this process only. Use a memory-backed emptyDir in Kubernetes."""
    safe = "".join(c if c.isalnum() or c in "-_." else "_" for c in component) or "default"
    path = runtime_dir() / f"{safe}.keytab"
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(data)
    return path


def check_gssapi() -> None:
    """Fail at startup, not at the first login, if the Kerberos stack is missing."""
    try:
        import krb5  # noqa: F401
        from gssapi.raw import inquire_sec_context_by_oid  # noqa: F401
    except ImportError as e:
        raise RuntimeError(f"Kerberos support is not installed (install smbprotocol[kerberos]): {e}") from e
