"""Kerberos plumbing: a generated krb5.conf, keytab files, and a startup check.

Tickets never touch disk. pyspnego obtains a TGT into a fresh MEMORY ccache
each time an SMB session is set up, from the password or the keytab, so
there is no shared ticket cache, no kinit and no refresher. What is
process-wide is the krb5 configuration file: MIT krb5 reads one per process,
so every component instance contributes its realm to a single generated file.
"""

from __future__ import annotations

import logging
import os
import pathlib
import threading
from dataclasses import dataclass

from .errors import Kind, SmbError

log = logging.getLogger(__name__)

RUNTIME_DIR_ENV = "SMB_BINDING_RUNTIME_DIR"
DEFAULT_RUNTIME_DIR = "/tmp/dapr-smb-binding"  # noqa: S108 - an emptyDir (medium: Memory) in Kubernetes


def runtime_dir() -> pathlib.Path:
    d = pathlib.Path(os.environ.get(RUNTIME_DIR_ENV) or DEFAULT_RUNTIME_DIR)
    d.mkdir(mode=0o700, parents=True, exist_ok=True)
    return d


@dataclass(frozen=True)
class RealmSpec:
    realm: str
    kdcs: tuple[str, ...]
    hosts: tuple[str, ...]  # file server FQDNs to map to this realm


class Krb5Config:
    """Merges the realms of all component instances into one krb5.conf."""

    def __init__(self, path: pathlib.Path | None = None):
        self._lock = threading.Lock()
        self._owners: dict[str, RealmSpec] = {}
        self._path = path

    @property
    def path(self) -> pathlib.Path:
        if self._path is None:
            self._path = runtime_dir() / "krb5.conf"
        return self._path

    def register(self, owner: str, spec: RealmSpec) -> None:
        with self._lock:
            self._owners[owner] = spec
            self._write()

    def unregister(self, owner: str) -> None:
        with self._lock:
            if self._owners.pop(owner, None) is not None:
                self._write()

    def render(self) -> str:
        return render(list(self._owners.values()))

    def _write(self) -> None:
        text = self.render()
        tmp = self.path.with_suffix(".tmp")
        tmp.write_text(text)
        tmp.chmod(0o644)
        tmp.replace(self.path)
        # MIT krb5 re-reads KRB5_CONFIG for every new krb5 context, and pyspnego
        # creates one per session setup, so updating the file is enough.
        os.environ["KRB5_CONFIG"] = str(self.path)
        # Belt and braces: nothing should use the default ccache, but if anything
        # does it must stay in memory.
        os.environ.setdefault("KRB5CCNAME", "MEMORY:dapr-smb-binding")


def render(specs: list[RealmSpec]) -> str:
    merged: dict[str, tuple[list[str], list[str]]] = {}
    for s in specs:
        kdcs, hosts = merged.setdefault(s.realm, ([], []))
        kdcs.extend(k for k in s.kdcs if k not in kdcs)
        hosts.extend(h for h in s.hosts if h not in hosts)

    # KDC discovery through DNS only when some realm has no explicit KDCs.
    dns_lookup_kdc = any(not kdcs for kdcs, _ in merged.values())
    default_realm = specs[0].realm if specs else ""

    lines = [
        "# Generated by dapr-smb-binding from component metadata. Do not edit.",
        "[libdefaults]",
    ]
    if default_realm:
        lines.append(f"    default_realm = {default_realm}")
    lines += [
        f"    dns_lookup_kdc = {'true' if dns_lookup_kdc else 'false'}",
        "    dns_lookup_realm = false",
        "    dns_canonicalize_hostname = false",
        "    rdns = false",
        # TCP only: works through Skupper and avoids UDP fragmentation with PACs.
        "    udp_preference_limit = 1",
        "    forwardable = false",
        "    default_ccache_name = MEMORY:dapr-smb-binding",
        "",
        "[realms]",
    ]
    for realm, (kdcs, _) in merged.items():
        lines.append(f"    {realm} = {{")
        lines.extend(f"        kdc = {k}" for k in kdcs)
        lines.append("    }")
    lines += ["", "[domain_realm]"]
    for realm, (_, hosts) in merged.items():
        lines.extend(f"    {h} = {realm}" for h in hosts)
    return "\n".join(lines) + "\n"


def write_keytab(owner: str, data: bytes) -> pathlib.Path:
    """Write a keytab for one component instance, readable by this process only.

    In Kubernetes the runtime directory should be an emptyDir with
    medium: Memory so the key never reaches a node disk.
    """
    safe = "".join(c if c.isalnum() or c in "-_." else "_" for c in owner) or "default"
    path = runtime_dir() / f"{safe}.keytab"
    fd = os.open(path.with_suffix(".tmp"), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(data)
    path.with_suffix(".tmp").replace(path)
    return path


def remove_keytab(path: pathlib.Path | None) -> None:
    if path is not None:
        try:
            path.unlink()
        except FileNotFoundError:
            pass


def check_gssapi() -> None:
    """Fail loudly if the Kerberos stack is incomplete.

    Without the GSSAPI extension pyspnego silently cannot do Kerberos, and in
    "negotiate" mode would fall back to NTLM. We never use negotiate, but an
    explicit check turns an obscure runtime failure into a clear startup one.
    """
    try:
        import krb5  # noqa: F401
        from gssapi.raw import inquire_sec_context_by_oid  # noqa: F401
    except ImportError as e:
        raise SmbError(
            Kind.CONFIG,
            "Kerberos support is not installed (python-gssapi and krb5 with MIT krb5 libraries); "
            f"install smbprotocol[kerberos]: {e}",
        ) from e


